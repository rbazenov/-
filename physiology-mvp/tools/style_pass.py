PREFIX = re.compile(r"^Верно:\s*")


def clean_explanation(text: str) -> str:
    text = PREFIX.sub("", text)
    if text:
        text = text[0].upper() + text[1:]
    return text


def apply_replacements(text: str) -> str:
    for old, new in REPLACEMENTS.items():
        if old in text:
            text = text.replace(old, new)
    return text


def process_item(item: dict) -> bool:
    changed = False
    if "title" in item:
        new_title = apply_replacements(item["title"])
        if new_title != item["title"]:
            item["title"] = new_title
            changed = True
    if "body_ru" in item:
        new = apply_replacements(item["body_ru"])
        if new != item["body_ru"]:
            item["body_ru"] = new
            changed = True
    if "options" in item:
        for opt in item["options"]:
            new_text = apply_replacements(opt["text_ru"])
            if new_text != opt["text_ru"]:
                opt["text_ru"] = new_text
                changed = True
            new = clean_explanation(opt["explanation_ru"])
            new = apply_replacements(new)
            if new != opt["explanation_ru"]:
                opt["explanation_ru"] = new
                changed = True
            if opt.get("hint_ru"):
                new_hint = apply_replacements(opt["hint_ru"])
                if new_hint != opt["hint_ru"]:
                    opt["hint_ru"] = new_hint
                    changed = True
        new_correct = clean_explanation(item.get("explanation_correct_ru", ""))
        new_correct = apply_replacements(new_correct)
        if new_correct != item.get("explanation_correct_ru"):
            item["explanation_correct_ru"] = new_correct
            changed = True
        new_prompt = apply_replacements(item["prompt_ru"])
        if new_prompt != item["prompt_ru"]:
            item["prompt_ru"] = new_prompt
            changed = True
    return changed


def main() -> int:
    total = 0
    for folder in FOLDERS:
        for name in ["cards.json", "questions.json", "delayed_checks.json"]:
            path = ROOT / "content" / "pilot" / folder / name
            data = json.loads(path.read_text(encoding="utf-8"))
            changed = 0
            for item in data:
                if process_item(item):
                    changed += 1
            if changed:
                path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            total += changed
            print(f"{folder}/{name}: {changed} items adjusted")
    print(f"Total items adjusted: {total}. Keys, attribution and review_status unchanged.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
